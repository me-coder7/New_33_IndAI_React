[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [ValidateSet('Jeswanth09052007', 'me-coder7', 'Purvaj-P22', 'BharanRajP', 'gurwinder-s24')]
    [string]$Member,
    [switch]$Stage,
    [string[]]$SharedFile = @(),
    [switch]$Commit,
    [switch]$AuthorApproved,
    [string]$Message
)
$ErrorActionPreference = 'Stop'
$root = (& git rev-parse --show-toplevel).Trim()
if ($LASTEXITCODE -ne 0) { throw 'Run inside the existing IndAI repository.' }
$manifestPath = Join-Path $root 'docs/team-commit-plan.json'
$manifest = Get-Content -LiteralPath $manifestPath -Raw | ConvertFrom-Json
$plan = @($manifest.members | Where-Object username -eq $Member)[0]
if (-not $plan) { throw 'Member is not present in the reviewed commit plan.' }
$branch = (& git branch --show-current).Trim()
$exclusive = @($plan.stageWholeFileCandidates)
$shared = @($plan.sharedFiles | ForEach-Object path)
$allowed = @($exclusive + $shared | Sort-Object -Unique)
$changed = @(& git -c core.quotepath=false diff --name-only HEAD)
if ($LASTEXITCODE -ne 0) { throw 'Cannot inspect working differences.' }
$untracked = @(& git -c core.quotepath=false ls-files --others --exclude-standard)
$changed = @($changed + $untracked | Sort-Object -Unique)

function Test-ImplementationPath([string]$Path) {
    return $Path -ne '.github/CODEOWNERS' -and
        $Path -notmatch '^docs/' -and $Path -notmatch '\.md$' -and
        $Path -notmatch '(^|/)(node_modules|dist|data|persistent-data|uploads|test-results)/' -and
        $Path -notmatch '\.(sqlite(-wal|-shm)?|db|log|zip)$'
}
$wholeChanges = @($changed | Where-Object { $_ -in $exclusive -and (Test-ImplementationPath $_) })
$sharedChanges = @($changed | Where-Object { $_ -in $shared -and (Test-ImplementationPath $_) })
$summary = [PSCustomObject]@{
    Member = $plan.username; Module = $plan.actor; ExpectedBranch = $plan.branch; CurrentBranch = $branch
    Author = $plan.name + ' <' + $plan.email + '>'
    WholeFileChanges = $wholeChanges; SharedChangesNeedingPartialStaging = $sharedChanges
    EligibleChangedPaths = $wholeChanges.Count + $sharedChanges.Count
    Status = if ($wholeChanges.Count + $sharedChanges.Count) { 'Review actual changes before staging.' } else { 'No new implementation changes; no teammate commit started.' }
}
if (-not $Stage -and -not $Commit) { $summary | ConvertTo-Json -Depth 4; return }
if ($branch -ne $plan.branch) { throw "Switch to '$($plan.branch)' before staging or committing this member's work." }

if ($Stage) {
    $alreadyStaged = @(& git diff --cached --name-only)
    if ($alreadyStaged.Count) { throw 'The index already contains changes. Preserve and review them; automatic staging stopped.' }
    if (-not $wholeChanges.Count -and -not $sharedChanges.Count) { throw 'No actual implementation changes exist. Empty commits are not created.' }
    if ($wholeChanges.Count) {
        & git --literal-pathspecs add -- @wholeChanges
        if ($LASTEXITCODE -ne 0) { throw 'Staging failed.' }
    }
    foreach ($path in $SharedFile) {
        if ($path -notin $shared -or $path -notin $sharedChanges) { throw "Not a changed shared file assigned to this member: $path" }
        Write-Output ('Assigned scope: ' + (@($plan.sharedFiles | Where-Object path -eq $path)[0].scope))
        & git --literal-pathspecs add -p -- $path
        if ($LASTEXITCODE -ne 0) { throw 'Partial staging failed.' }
    }
}

$staged = @(& git -c core.quotepath=false diff --cached --name-only)
if (-not $staged.Count) { throw 'No reviewed changes are staged. No commit was created.' }
$unrelated = @($staged | Where-Object { $_ -notin $allowed })
if ($unrelated.Count) { throw ('Unrelated staged paths must be reviewed separately: ' + ($unrelated -join ', ')) }
if (-not @($staged | Where-Object { Test-ImplementationPath $_ }).Count) {
    throw 'Only ownership/documentation changes are staged. They do not establish a module implementation contribution.'
}
& (Join-Path $root 'scripts/Test-StagedSecrets.ps1')
& git diff --cached --check
if ($LASTEXITCODE -ne 0) { throw 'Staged whitespace review failed.' }
& git diff --cached --stat
if ($Commit) {
    if (-not $AuthorApproved) { throw 'Real author approval is required; no commit was created.' }
    if ([string]::IsNullOrWhiteSpace($Message) -or $Message -eq 'Describe the actual module change') {
        throw 'Provide a message describing the actual implemented change.'
    }
    # The committer remains the actual configured integrator. Author approval is
    # an explicit attestation, not proof generated by an ownership assignment.
    $author = $plan.name + ' <' + $plan.email + '>'
    & git commit --author=$author --message=$Message
    if ($LASTEXITCODE -ne 0) { throw 'Commit failed; no push was attempted.' }
    & git log -1 '--format=%h | author=%an <%ae> | committer=%cn <%ce> | %s'
    Write-Output 'Commit created. Review it and run the relevant tests before pushing. This script never pushes.'
}
